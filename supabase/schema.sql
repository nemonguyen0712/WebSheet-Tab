-- One row per account (created at sign-up). Sign-in is by username or phone + password.
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  phone text not null unique, -- 84901234567
  username text not null unique check (username ~ '^[a-z0-9._]{3,20}$'),
  paid_until timestamptz,
  created_at timestamptz not null default now()
);

-- Browsers an account is signed in on (limited to MAX_DEVICES).
create table if not exists public.devices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  user_agent text,
  created_at timestamptz not null default now(),
  last_seen timestamptz not null default now()
);
create index if not exists devices_user_idx on public.devices (user_id, created_at desc);

-- Payment orders. order_code is the number shown in the bank transfer note (TAB100001…).
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_code bigint generated by default as identity (start with 100001) unique,
  user_id uuid not null references public.profiles (id) on delete cascade,
  plan text not null,
  days int not null,
  amount int not null,
  provider text not null,
  status text not null default 'pending' check (status in ('pending', 'paid', 'cancelled')),
  checkout_url text,
  provider_ref text,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);
create index if not exists orders_user_idx on public.orders (user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.devices enable row level security;
alter table public.orders enable row level security;
-- No policies: only the service role (the server) can read or write these tables.

-- Marks an order paid (once) and extends the buyer's subscription. Safe to call repeatedly,
-- e.g. from both the payment webhook and the return page.
create or replace function public.mark_order_paid(p_order_code bigint, p_amount int, p_ref text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  o public.orders;
begin
  update public.orders
     set status = 'paid', paid_at = now(), provider_ref = p_ref
   where order_code = p_order_code and status = 'pending' and amount <= p_amount
  returning * into o;
  if not found then
    return false;
  end if;
  update public.profiles
     set paid_until = greatest(coalesce(paid_until, now()), now()) + make_interval(days => o.days)
   where id = o.user_id;
  return true;
end;
$$;

-- Admin: add (or with negative days, remove) subscription time.
create or replace function public.extend_subscription(p_user uuid, p_days int)
returns timestamptz
language sql
security definer
set search_path = public
as $$
  update public.profiles
     set paid_until = greatest(coalesce(paid_until, now()), now()) + make_interval(days => p_days)
   where id = p_user
  returning paid_until;
$$;

revoke all on function public.mark_order_paid(bigint, int, text) from public, anon, authenticated;
revoke all on function public.extend_subscription(uuid, int) from public, anon, authenticated;
grant execute on function public.mark_order_paid(bigint, int, text) to service_role;
grant execute on function public.extend_subscription(uuid, int) to service_role;

-- Log of full-file views: rate limiting per account and spotting bulk downloads.
create table if not exists public.file_views (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  file_id text not null,
  created_at timestamptz not null default now()
);
create index if not exists file_views_user_idx on public.file_views (user_id, created_at desc);
create index if not exists file_views_time_idx on public.file_views (created_at desc);
alter table public.file_views enable row level security;

-- Admin page: who viewed the most since a given time.
create or replace function public.file_view_stats(p_since timestamptz)
returns table (user_id uuid, username text, phone text, views bigint, files bigint)
language sql
security definer
set search_path = public
as $$
  select v.user_id, p.username, p.phone, count(*), count(distinct v.file_id)
    from public.file_views v
    join public.profiles p on p.id = v.user_id
   where v.created_at >= p_since
   group by v.user_id, p.username, p.phone
   order by count(distinct v.file_id) desc
   limit 20;
$$;
revoke all on function public.file_view_stats(timestamptz) from public, anon, authenticated;
grant execute on function public.file_view_stats(timestamptz) to service_role;

-- Google Drive folders added from /admin (besides DRIVE_FOLDER_ID in the server's environment).
create table if not exists public.drive_folders (
  id text primary key,
  label text not null default '',
  -- 'solo' / 'melody': the whole folder is that section; null: its Solo / Melody subfolders tell them apart.
  section text check (section in ('solo', 'melody')),
  created_at timestamptz not null default now()
);
alter table public.drive_folders enable row level security;

-- Songs customers ask to be added (page /yeu-cau, handled in /admin). A few per calendar month per account;
-- a rejected request doesn't count, so the customer gets that request back.
create table if not exists public.song_requests (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  title text not null,
  section text not null default '' check (section in ('', 'solo', 'melody')),
  detail text not null default '',
  status text not null default 'pending' check (status in ('pending', 'done', 'rejected')),
  admin_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists song_requests_user_idx on public.song_requests (user_id, created_at desc);
create index if not exists song_requests_status_idx on public.song_requests (status, created_at);
alter table public.song_requests enable row level security;
